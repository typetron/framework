import { ColumnDefinitionOptions } from '.'
import { wrap } from '../../Helpers'

export class ColumnDefinition {
    /** SQL standard identity column; dialects with their own syntax override it */
    autoIncrement = 'GENERATED BY DEFAULT AS IDENTITY'

    constructor(public options: ColumnDefinitionOptions) {}

    toSQL() {
        const sqlParts = [wrap(this.options.name), this.options.type]

        if (this.options.autoIncrement) {
            sqlParts.push(this.autoIncrement)
        }

        return sqlParts.join(' ')
    }
}

export type ColumnDefinitionConstructor = new (options: ColumnDefinitionOptions) => ColumnDefinition
