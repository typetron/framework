import { ColumnDefinitionOptions } from '..'
import { wrap } from '../../../Helpers'
import { Expression } from '../../../Expression'
import { ColumnDefinition, ColumnDefinitionConstructor } from '../ColumnDefinition'

export enum Constraints {
    PrimaryKey = 'PRIMARY KEY',
    ForeignKey = 'FOREIGN KEY',
}

export abstract class AlterOption extends Expression {
    constructor(public column: ColumnDefinitionOptions) {super()}

    abstract toSQL(): string
}

export class AddColumn extends AlterOption {
    protected columnDefinition: ColumnDefinitionConstructor = ColumnDefinition

    toSQL(): string {
        return `ADD ${new this.columnDefinition(this.column).toSQL()}`
    }
}

export class AlterColumnType extends AlterOption {
    toSQL(): string {
        const column = wrap(this.column.name)
        return `ALTER COLUMN ${column} TYPE ${this.column.type} USING ${column}::${this.column.type}`
    }
}

export class AddIdentity extends AlterOption {
    toSQL(): string {
        const column = wrap(this.column.name)
        return `ALTER COLUMN ${column} SET NOT NULL, ALTER COLUMN ${column} ADD GENERATED BY DEFAULT AS IDENTITY`
    }
}

export class AddPrimaryKey extends AlterOption {
    toSQL(): string {
        return `ADD PRIMARY KEY (${wrap(this.column.name)})`
    }
}

export class AddConstraint extends AlterOption {

    constructor(column: ColumnDefinitionOptions, public type: Constraints) {super(column)}

    toSQL(): string {
        return `ADD CONSTRAINT ${this.type} (${wrap(this.column.name)})`
    }
}

export class AddForeignKey extends Expression {
    constructor(public table: string, public column: string, public relatedTable: string, public relatedColumn: string) {
        super()
    }

    toSQL(): string {
        const name = `${this.table}_${this.column}_foreign`
        return `ADD CONSTRAINT ${wrap(name)} ${Constraints.ForeignKey} (${wrap(this.column)})
                REFERENCES ${wrap(this.relatedTable)} (${wrap(this.relatedColumn)})`
    }
}

export class DropColumn extends Expression {
    constructor(public column: string) {super()}

    toSQL(): string {
        return `DROP COLUMN ${wrap(this.column)}`
    }
}

export class Alter extends Expression {
    constructor(public table: string, public alterOptions: Expression[]) {super()}

    toSQL() {
        return `
            ALTER TABLE ${wrap(this.table)}
                ${this.alterOptions.map(option => option.toSQL()).join(', \n')}
        `
    }
}
