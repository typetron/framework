import { suite, test } from '@testdeck/mocha'
import { expect } from 'chai'
import { BelongsTo, Column, Entity, HasMany, ID, JSONColumn, Options, PostgresDriver, PrimaryColumn, Relation } from '@Typetron/Database'
import { anyString, instance, mock, when } from 'ts-mockito'
import { Schema } from '@Typetron/Database/Drivers/Postgres/Schema'
import { expectQuery } from '../utils'
import { DatabaseDriver } from '@Typetron/Database/Drivers/DatabaseDriver'

@suite
class PostgresDriverTest {

    driver: DatabaseDriver
    schema: Schema
    queries: string[]

    async before() {
        this.queries = []
        this.driver = mock(PostgresDriver)
        this.schema = new Schema(instance(this.driver))
        when(this.driver.run(anyString())).thenCall((query: string) => this.queries.push(query))
    }

    @test
    async addsMissingForeignKeysAfterCreatingTheTables() {
        @Options({table: 'authors'})
        class Author extends Entity {
            @PrimaryColumn()
            id: ID

            @Relation(() => Book, 'author')
            books: HasMany<Book>
        }

        @Options({table: 'books'})
        class Book extends Entity {
            @PrimaryColumn()
            id: ID

            @Relation(() => Author, 'books')
            author: BelongsTo<Author>
        }

        when(this.driver.tableForeignKeys('books')).thenResolve([])
        await this.schema.synchronize([Book, Author].pluck('metadata'))
        expectQuery(this.queries[2]).toEqual(`
            ALTER TABLE \`books\`
                ADD CONSTRAINT \`books_authorId_foreign\` FOREIGN KEY (\`authorId\`)
                    REFERENCES \`authors\` (\`id\`)
        `)

        this.queries = []
        when(this.driver.tableExists(anyString())).thenResolve(true)
        when(this.driver.tableColumns(anyString())).thenResolve([])
        when(this.driver.tableForeignKeys('books')).thenResolve(['authorId'])
        await this.schema.synchronize([Book, Author].pluck('metadata'))
        expect(this.queries.filter(query => query.includes('FOREIGN KEY'))).to.deep.equal([])
    }

    @test
    async createsTableWithIdentityPrimaryColumn() {
        @Options()
        class Test extends Entity {
            @PrimaryColumn()
            id: ID

            @Column()
            name: string

            @Column()
            active: boolean

            @Column()
            createdAt: Date
        }

        await this.schema.synchronize([Test].pluck('metadata'))
        expectQuery(this.queries[0]).toEqual(`
            CREATE TABLE Test
            (
                id integer GENERATED BY DEFAULT AS IDENTITY,
                name varchar(255),
                active boolean,
                createdAt timestamp,
                PRIMARY KEY (id)
            )
        `)
    }

    @test
    async createsNativeJSONColumns() {
        @Options()
        class Test extends Entity {
            @PrimaryColumn()
            id: ID

            @JSONColumn()
            settings: Record<string, string>
        }

        await this.schema.synchronize([Test].pluck('metadata'))
        expectQuery(this.queries[0]).toEqual(`
            CREATE TABLE Test
            (
                id integer GENERATED BY DEFAULT AS IDENTITY,
                settings jsonb,
                PRIMARY KEY (id)
            )
        `)
    }

    @test
    async altersTable() {
        when(this.driver.tableExists(anyString())).thenReturn(Promise.resolve(true))
        when(this.driver.tableColumns(anyString())).thenReturn(Promise.resolve([
            {name: 'column2', type: 'integer'},
            {name: 'column3', type: 'integer'},
        ]))

        class User extends Entity {
            @Column()
            column1: number

            @Column()
            column2: string
        }

        await this.schema.synchronize([User].pluck('metadata'))

        expectQuery(this.queries[0]).toEqual(`
            ALTER TABLE User
                ADD column1 integer,
                ALTER COLUMN column2 TYPE varchar(255) USING column2::varchar(255),
                DROP COLUMN column3
        `)
    }

    @test
    async leavesUnchangedTableAlone() {
        when(this.driver.tableExists(anyString())).thenReturn(Promise.resolve(true))
        when(this.driver.tableColumns(anyString())).thenReturn(Promise.resolve([
            {name: 'id', type: 'integer', primaryKey: true, autoIncrement: 1},
        ]))

        class User extends Entity {
            @PrimaryColumn()
            id: ID
        }

        await this.schema.synchronize([User].pluck('metadata'))

        expect(this.queries).to.be.empty
    }

    @test
    async altersTableAddPrimaryKey() {
        when(this.driver.tableExists(anyString())).thenReturn(Promise.resolve(true))
        when(this.driver.tableColumns(anyString())).thenReturn(Promise.resolve([]))

        class User extends Entity {
            @PrimaryColumn()
            id: ID
        }

        await this.schema.synchronize([User].pluck('metadata'))

        expectQuery(this.queries[0]).toEqual('ALTER TABLE User ADD id integer')
        expectQuery(this.queries[1]).toEqual(`
            ALTER TABLE User
                ADD PRIMARY KEY (id),
                ALTER COLUMN id SET NOT NULL,
                ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY
        `)
    }
}
